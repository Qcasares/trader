"""
test_web_sources.py
-------------------
The allow-list, the README parser, the excerpt normaliser and the code screen:
``src/programme/web_sources.py``, pure, so all of it is tested here with no
network and no database.

Every fixture is synthetic. The paperswithbacktest repository publishes no
licence, so no title, figure or line of its README is copied here: the README
below keeps only the shape the parser reads — the generator's markers, the
level-two headings, the five-column table — around titles invented for the
purpose and figures that are sentinels, numbers that appear nowhere else, so
that one surviving into an excerpt would be seen.

What must hold:

* only the one allow-listed page, written out exactly, can be fetched; the
  module checks it when it loads and records it as written; and nothing in
  ``src/`` edits the list by any spelling the scan knows;
* the parser keeps titles and nothing else — no figure, link or heading — from
  inside the markers only, and refuses a page that has changed shape, a line
  it cannot read among them, for each reason it names, with a message that
  carries none of the page's text, and no line holds it for long;
* the normaliser is idempotent, and no address, Markdown link, control,
  format, unassigned or default-ignorable character or NUL survives it, while
  HTML does, for the screen to see; and no title holds it for long;
* the code screen reads a keyword however it is decorated — emphasis,
  accents, lookalike letters — and ``code-screen v1`` names one rule set,
  pinned beside the rules and by a released history here;
* each adversarial case has one pinned fate — dropped by the parser, dropped
  or quarantined by :func:`web_sources.screen_cell`, or the snapshot refused —
  and only words that themselves trip the screen are ever quarantined;
* seeded fuzz of the page raises nothing but ``SnapshotRefused``;
* the module loads nothing heavy, so the API can import it.
"""

