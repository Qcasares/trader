_GOOD = [_row(f"A Plain Invented Title {n}", f"plain-{n}") for n in "abcdef"]


def _fate(row: str) -> str:
    """
    What becomes of one row among plain ones: ``drop`` if the parser does not
    keep it; otherwise what :func:`web_sources.screen_cell`, which the ingest
    job stores, decides — ``keep``, ``quarantine:<rule>`` for words that trip
    the screen, ``drop:<rule>`` for a cell only its decoration tripped, and
    ``drop:empty`` for one that normalises to nothing.
    """
    snapshot = parse_pwb_readme(_readme([("Equities", [*_GOOD, row])]))
    kept = [e.cell for e in snapshot.entries if "Plain Invented" not in e.cell]
    if not kept:
        assert snapshot.dropped == 1
        return "drop"
    [cell] = kept
    screened = ws.screen_cell(cell)
    if screened.fate == "keep":
        return "keep"
    return f"{screened.fate}:{screened.rule or 'empty'}"


