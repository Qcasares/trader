def _row(
    title: str,
    slug: str = "an-invented-strategy",
    figures: Sequence[str] = (SHARPE, T_STAT, VOLATILITY, YEARS),
) -> str:
    sharpe, t_stat, volatility, years = figures
    return (
        f"| [{title}]({STRATEGY_PAGE}{slug}) | `{sharpe}` | `{t_stat}` | "
        f"`{volatility}` | `{years}` |"
    )


def _block(sections: Iterable[tuple[str, Sequence[str]]]) -> list[str]:
    lines = [
        "*An invented note on how the table below was generated.*",
        "",
    ]
    for heading, rows in sections:
        lines += [f"## {heading}", "", HEADER, DELIMITER, *rows, ""]
    return lines


def _readme(
    sections: Iterable[tuple[str, Sequence[str]]] | None = None,
    *,
    start: str = START_LINE,
    end: str = ws.END_MARKER,
) -> str:
    """
    A README with the table between the markers, and, outside them, the kinds
    of thing the real page has there: other headings — ``## Crypto`` among
    them, as the books section has — and a table the parser must not read.
    """
    if sections is None:
        sections = [
            (heading, [_row(t, f"slug-{i}") for i, t in enumerate(titles)])
            for heading, titles in TITLES.items()
        ]
    outside = [
        "## Crypto",
        "",
        HEADER,
        DELIMITER,
        _row("An Outside Row That Must Not Be Read", "outside"),
        "",
    ]
    return "\n".join(
        [
            "# An Invented Awesome List",
            "",
            *outside,
            "# Strategies",
            "",
            start,
            "",
            *_block(sections),
            end,
            "",
            "# Books",
            "",
            *outside,
        ]
    )


def _entries(text: str) -> list[tuple[str, str]]:
    return [(e.label, e.cell) for e in parse_pwb_readme(text).entries]


def _excerpts(text: str) -> list[str]:
    return [normalise_excerpt(e.cell) for e in parse_pwb_readme(text).entries]


