def test_web_sources_loads_nothing_heavy() -> None:
    """
    Importing it, in a fresh interpreter, loads nothing that can reach a
    network, a database or a model, and nothing of the programme but the pure
    modules it names: the API may import it to show the allow-list.
    """
    code = (
        "import sys\n"
        "before = set(sys.modules)\n"
        "import src.programme.web_sources\n"
        "print('\\n'.join(sorted(set(sys.modules) - before)))\n"
    )
    result = subprocess.run(
        [sys.executable, "-c", code],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    loaded = set(result.stdout.split())
    ours = {name for name in loaded if name == "src" or name.startswith("src.")}
    assert ours <= {
        "src",
        "src.programme",
        "src.programme.web_sources",
        "src.programme.jev_hash",
        "src.programme.jev_questions",
        "src.programme.jev_catalogue",
    }, ours
    assert "src.programme.web_sources" in ours
    forbidden = (
        "aiohttp",
        "anthropic",
        "asyncpg",
        "httpx",
        "httpx2",
        "requests",
        "typesafe_sdk",
        "urllib3",
        "yfinance",
        "src.db",
        "src.programme.jev_client",
        "src.programme.jev_lane",
        "src.programme.jev_features",
        "src.programme.web_fetch",
    )
    reached = sorted(
        name
        for name in loaded
        if any(name == f or name.startswith(f + ".") for f in forbidden)
    )
    assert reached == [], reached
