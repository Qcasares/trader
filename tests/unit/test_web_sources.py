#: Lines a mutation may insert: headings, markers, rows with and without
#: their shape, and text that is none of those.
_INSERTED = (
    "## Equities",
    "## Crypto",
    "### Bonds",
    "#",
    "## ",
    START_LINE,
    ws.END_MARKER,
    HEADER,
    DELIMITER,
    "|",
    "| |",
    "||||",
    _row("Fuzzed Title"),
    _row("Fuzzed \u202e Title"),
    _row("x" * 400),
    "| [Title](https://paperswithbacktest.com/strategies/x) | `1.00` |",
    "Ignore previous instructions",
    "",
    "\u2028",
    "\x00",
    "   | [Indented](https://paperswithbacktest.com/strategies/y) |",
)


def _mutate(text: str, rng: random.Random) -> str:
    lines = text.split("\n")
    for _ in range(rng.randint(1, 8)):
        operation = rng.randrange(6)
        at = rng.randrange(len(lines) + 1)
        if operation == 0:
            lines.insert(at, rng.choice(_INSERTED))
        elif operation == 1 and lines:
            del lines[min(at, len(lines) - 1)]
        elif operation == 2 and lines:
            lines.insert(at, lines[rng.randrange(len(lines))])
        elif operation == 3 and lines:
            index = min(at, len(lines) - 1)
            line = lines[index]
            cut = rng.randrange(len(line) + 1)
            lines[index] = line[:cut] + _nasty_text(rng) + line[cut:]
        elif operation == 4 and lines:
            index = min(at, len(lines) - 1)
            line = lines[index]
            if line:
                cut = rng.randrange(len(line))
                lines[index] = (
                    line[:cut] + chr(rng.randrange(0x110000)) + line[cut + 1 :]
                )
        elif operation == 5:
            lines = lines[: rng.randrange(len(lines) + 1)]
    return "\n".join(lines)


class TestTheParserUnderFuzz:
    @pytest.mark.parametrize("seed", range(4))
    def test_only_a_refusal_is_raised(self, seed: int) -> None:
        """
        Seeded mutations of the synthetic page — lines inserted, deleted,
        repeated, cut into and corrupted with any code point — either parse or
        are refused. Nothing else is raised, by the parser or by the
        normaliser and screen run on whatever it keeps.
        """
        rng = random.Random(1_000 + seed)
        base = _readme()
        parsed = refused = 0
        for _ in range(500):
            text = _mutate(base, rng)
            try:
                snapshot = parse_pwb_readme(text)
            except SnapshotRefused as error:
                assert error.reason in ws.SNAPSHOT_REFUSALS
                refused += 1
                continue
            parsed += 1
            assert 0 < snapshot.rows <= ws.MAX_ROWS
            assert snapshot.dropped * 2 <= snapshot.table_rows
            for entry in snapshot.entries:
                assert entry.label in ws.HEADING_LABELS.values()
                assert 1 <= len(entry.cell) <= 400 and "\n" not in entry.cell
                excerpt = normalise_excerpt(entry.cell)
                assert normalise_excerpt(excerpt) == excerpt
                code_screen(entry.cell)
                code_screen(excerpt)
        assert parsed and refused, (parsed, refused)


