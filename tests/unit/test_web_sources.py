#: The hash of every released version of the code screen, append-only, kept
#: here as history apart from the rules it pins. A quarantine records
#: ``code-screen v<N>: <rule>``, so v1 must name one rule set for as long as a
#: row says it. ``web_sources.GOLDEN_CODE_SCREEN_SHA256`` sits beside the
#: rules, so re-recording it is exactly the edit a developer makes when a hash
#: test fails; changing a released version's rules therefore also takes an edit
#: to this history, which a reviewer sees for what it is. v1 was re-recorded
#: once, before any row could say it, when review revised its rules (docs/08,
#: "Phase C, as built", C5).
RELEASED_CODE_SCREEN_HASHES = {
    1: "95cc9a98bff72231934da34b8d475668af04ee84a966c86073850958e88e1984",
}


def _screen_release_problems(module: types.ModuleType) -> list[str]:
    """How the code screen in ``module`` differs from what was released."""
    version = module.CODE_SCREEN_VERSION
    released = RELEASED_CODE_SCREEN_HASHES.get(version)
    if released is None:
        return [f"v{version} is not in RELEASED_CODE_SCREEN_HASHES: append it"]
    problems: list[str] = []
    hashed = module.code_screen_sha256()
    if hashed != released:
        problems.append(
            f"v{version} hashes to {hashed}, but was released as {released}: a "
            "released version's rules are frozen, so bump the version and "
            "append a row"
        )
    if module.GOLDEN_CODE_SCREEN_SHA256 != released:
        problems.append(f"v{version}'s golden disagrees with its release")
    newest = max(RELEASED_CODE_SCREEN_HASHES)
    if version != newest:
        problems.append(f"v{version} is in use, but v{newest} was released")
    return problems


