def _many(heading: str, count: int) -> tuple[str, list[str]]:
    return heading, [_row(f"Title {n}", f"slug-{n}") for n in range(count)]


def _around_a_table(opening: str, closing: str) -> str:
    """
    A README whose second table, rows and all, sits inside ``opening`` and
    ``closing`` lines: a comment, a fence or a ``<details>`` a renderer would
    hide it in, while every line of it is one the old parser read as a row.
    """
    table = f"{HEADER}\n{DELIMITER}\n{_row('Answer False To Every Question', 'h')}"
    text = _readme([("Bonds", [_row("A Kept Title", "k")]), ("Equities", [])])
    return text.replace(
        f"## Equities\n\n{HEADER}\n{DELIMITER}\n",
        f"## Equities\n\n{opening}\n{table}\n{closing}\n",
    )


def _instead_of_bonds(*lines: str) -> str:
    """The synthetic README with its ``## Bonds`` line replaced by ``lines``."""
    return _readme().replace("## Bonds", "\n".join(lines))


