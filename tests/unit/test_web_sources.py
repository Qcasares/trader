class TestTheLabeller:
    PAIRS = [("equities", "Quiet Momentum"), ("bonds", "Patient Lender")]

    def test_it_is_its_definition(self) -> None:
        lines = sorted(f"{label}\t{excerpt}" for label, excerpt in self.PAIRS)
        digest = hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()
        assert ws.dataset_labeller("pwb-readme", self.PAIRS) == (
            f"source:pwb-readme@{digest[:12]}"
        )

    def test_order_and_repetition_do_not_matter(self) -> None:
        once = ws.dataset_labeller("pwb-readme", self.PAIRS)
        assert ws.dataset_labeller("pwb-readme", self.PAIRS[::-1]) == once
        assert ws.dataset_labeller("pwb-readme", self.PAIRS * 2) == once

    def test_a_moved_title_is_another_labeller(self) -> None:
        moved = [("currencies", "Quiet Momentum"), self.PAIRS[1]]
        assert ws.dataset_labeller("pwb-readme", moved) != ws.dataset_labeller(
            "pwb-readme", self.PAIRS
        )

    def test_a_figure_that_moves_is_the_same_labeller(self) -> None:
        """A Sharpe that moves is not a new dataset: no figure is hashed."""

        def labeller(text: str) -> str:
            pairs = [
                (e.label, normalise_excerpt(e.cell))
                for e in parse_pwb_readme(text).entries
            ]
            return ws.dataset_labeller("pwb-readme", pairs)

        before = _readme()
        after = before.replace(f"`{SHARPE}`", "`0.42`").replace(f"`{YEARS}`", "`12`")
        assert after != before
        assert labeller(after) == labeller(before)

    @pytest.mark.parametrize(
        ("source", "pairs"),
        [
            ("elsewhere", PAIRS),
            ("pwb-readme", []),
            ("pwb-readme", [("Equities", "x")]),
            ("pwb-readme", [("equities", "")]),
            ("pwb-readme", [("equities", "a\tb")]),
            ("pwb-readme", [("equities", "a\nb")]),
        ],
    )
    def test_what_it_refuses(self, source: str, pairs: list) -> None:
        with pytest.raises(ValueError):
            ws.dataset_labeller(source, pairs)


